  const skipped = element => element?.closest('.message-content, [data-no-translate], code, pre, script, style');
  const translated = value => {
    if (es[value]) return es[value];
    return replacements.reduce((result, [pattern, replacement]) => result.replace(pattern, replacement), value);
  };
  const translateTextNode = node => {
    if (skipped(node.parentElement)) return;
    const match = node.nodeValue.match(/^(\s*)(.*?)(\s*)$/s);
    if (!match || !match[2]) return;
    const value = translated(match[2]);
    if (value !== match[2]) node.nodeValue = `${match[1]}${value}${match[3]}`;
  };
  const translateElement = element => {
    if (!(element instanceof Element) || skipped(element)) return;
    for (const attribute of ['placeholder', 'title', 'aria-label']) {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translated(value));
    }
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node);
  };

  translateElement(document.documentElement);
  for (const [source, target] of Object.entries(es)) {
    if (document.title === source || document.title.startsWith(`${source} ·`)) {
      document.title = document.title.replace(source, target);
      break;
    }
  }
  new MutationObserver(records => {
    for (const record of records) {
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else if (node.nodeType === Node.ELEMENT_NODE) translateElement(node);
      }
    }
  }).observe(document.body, {childList: true, subtree: true});

